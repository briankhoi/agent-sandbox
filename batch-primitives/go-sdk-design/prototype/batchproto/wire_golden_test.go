// Inputs where Python's int()/float()/re/str.isdigit are laxer than Go's strconv/regexp. None of these
// can be produced by either SDK's writer; they only arise from hand-edited objects. Each is listed so
// the divergence is explicit and reviewed, instead of hidden.
var knownLaxPython = map[string]string{
	"lease_decode/batch-work-budget='99999999999999999999'": "Python int is unbounded; Go rejects at GetBatch (Python fails later, at acquire, in datetime arithmetic)",
	"lease_decode/batch-create-rps=' 50 '":                  "Python float() strips whitespace",
	"lease_decode/batch-lease-duration=' 7 '":               "Python int() strips whitespace",
	"lease_decode/batch-lease-duration='1_0'":               "Python int() accepts digit underscores",
	"lease_decode/batch-work-budget=' 2'":                   "Python int() strips whitespace",
	"lease_decode/batch-work-budget='٣'":                    "Python int() accepts Unicode digits",
	"reconstruct_groups/whitespace int":                     "Python int() strips whitespace",
	// rev 3.2: validate_batch_id("a\n") (aecbdb40, fullmatch) and the Unicode-digit Retry-After
	// entries "٣"/"²" (924e8016, isascii) were dropped: Python now agrees with Go on all three.
}

type golden struct {
	Generator map[string]string `json:"generator"`
	FillPlan  []struct {
		BatchID string `json:"batch_id"`
		Groups  []struct {
			WarmPool string `json:"warmpool"`
			Size     int    `json:"size"`
			MinReady int    `json:"min_ready"`
		} `json:"groups"`
		Plan [][2]string `json:"plan"`
	} `json:"fill_plan"`
	GroupLabel []struct{ WarmPool, Value, Selector string } `json:"group_label"`
	Args       []struct {
		Name   string `json:"name"`
		Input  map[string]any
		Result struct {
			OK    bool `json:"ok"`
			Value *struct {
				CreateRPS        float64           `json:"create_rps"`
				WorkBudget       int               `json:"work_budget"`
				QuorumTimeout    int               `json:"quorum_timeout"`
				LeaseDuration    int               `json:"lease_duration"`
				LeaseLabels      map[string]string `json:"lease_labels"`
				LeaseAnnotations map[string]string `json:"lease_annotations"`
			} `json:"value"`
		} `json:"result"`
	} `json:"claim_batch_args"`
	LabelValidation []struct {
		Kind string `json:"kind"`
		S    string `json:"s"`
		OK   bool   `json:"ok"`
	} `json:"label_validation"`
	LeaseDecode []struct {
		Name        string            `json:"name"`
		Labels      map[string]string `json:"labels"`
		Annotations map[string]string `json:"annotations"`
		Result      struct {
			OK    bool            `json:"ok"`
			Value json.RawMessage `json:"value"`
		} `json:"result"`
	} `json:"lease_decode"`
	DeriveMember []struct {
		Name   string          `json:"name"`
		Claim  json.RawMessage `json:"claim"`
		Member Member          `json:"member"`
	} `json:"derive_member"`
	Reconstruct []struct {
		Name    string            `json:"name"`
		BatchID string            `json:"batch_id"`
		Claims  []json.RawMessage `json:"claims"`
		Result  struct {
			OK    bool        `json:"ok"`
			Value []groupJSON `json:"value"`
		} `json:"result"`
	} `json:"reconstruct_groups"`
	ParseOrdinal []struct {
		BatchID string `json:"batch_id"`
		Name    string `json:"name"`
		Ordinal *int   `json:"ordinal"`
	} `json:"parse_ordinal"`
	ValidateID []struct {
		ID string `json:"id"`
		OK bool   `json:"ok"`
	} `json:"validate_batch_id"`
	Stale []struct {
		Renew, Now string
		Duration   int
		Stale      bool
	} `json:"is_lease_stale"`
	Outcome []struct {
		Status  *int   `json:"status"`
		Attempt int    `json:"attempt"`
		Outcome string `json:"outcome"`
	} `json:"create_error_outcome"`
	RetryAfter []struct {
		Header   string   `json:"header"`
		Honoured bool     `json:"honoured"`
		Delay    *float64 `json:"delay"`
	} `json:"retry_after"`
	Backoff []struct {
		Attempt int     `json:"attempt"`
		Rand    float64 `json:"rand"`
		Delay   float64 `json:"delay"`
	} `json:"backoff"`
	Shutdown []struct {
		Size          int     `json:"size"`
		CreateRPS     float64 `json:"create_rps"`
		QuorumTimeout int     `json:"quorum_timeout"`
		WorkBudget    int     `json:"work_budget"`
		FillSeconds   float64 `json:"fill_seconds"`
		AcqSeconds    int64   `json:"acquire_seconds"`
	} `json:"shutdown_seconds"`
}

func TestGoldenParity(t *testing.T) {
	raw, err := os.ReadFile("testdata/batch_golden.json")
	if err != nil {
		t.Fatal(err)
	}
	var g golden
	if err := json.Unmarshal(raw, &g); err != nil {
		t.Fatal(err)
	}
	t.Logf("fixtures generated by %v", g.Generator)
	var checked, allowed int
	check := func(id string, equal bool, got, want any) {
		checked++
		if equal {
			return
		}
		if why, ok := knownLaxPython[id]; ok {
			allowed++
			t.Logf("ALLOWED divergence %s: go=%v python=%v (%s)", id, got, want, why)
			return
		}
		t.Errorf("MISMATCH %s:\n  go:     %v\n  python: %v", id, got, want)
	}

	for _, c := range g.FillPlan {
		var groups []BatchGroup
		for _, gr := range c.Groups {
			mr := gr.MinReady
			groups = append(groups, BatchGroup{gr.WarmPool, gr.Size, &mr})
		}
		var got [][2]string
		for _, p := range fillCreatePlan(c.BatchID, groups) {
			got = append(got, [2]string{p.ClaimName, groups[p.Group].WarmPool})
		}
		check(fmt.Sprintf("fill_plan/%s/%v", c.BatchID, c.Groups), reflect.DeepEqual(got, c.Plan) || (len(got) == 0 && len(c.Plan) == 0), got, c.Plan)
	}
	for _, c := range g.GroupLabel {
		check("group_label/"+c.WarmPool, groupLabelValue(c.WarmPool) == c.Value && groupLabelSelector("bid", c.WarmPool) == c.Selector, groupLabelValue(c.WarmPool), c.Value)
	}
	for _, c := range g.Args {
		if !c.Result.OK || c.Result.Value == nil {
			continue // validation errors are covered by the API-shape tests; Go uses Durations, see doc
		}
		v := c.Result.Value
		lbl := map[string]string{}
		if l, ok := c.Input["labels"].(map[string]any); ok {
			for k, x := range l {
				lbl[k] = x.(string)
			}
		}
		gl, ga := batchLeaseMetadata(lbl, c.Input["batch_id"].(string), v.LeaseDuration, v.WorkBudget, v.QuorumTimeout, v.CreateRPS)
		wantL := map[string]string{}
		for k, x := range v.LeaseLabels {
			wantL[k] = x
		}
		wantL[createdByLabel] = "go-client" // SDK-specific and stripped on parse
		check("lease_encode/"+c.Name, reflect.DeepEqual(gl, wantL) && reflect.DeepEqual(ga, v.LeaseAnnotations), fmt.Sprint(gl, ga), fmt.Sprint(wantL, v.LeaseAnnotations))
		// round trip: what Go writes, Python-shaped parse gives back
		s, err := parseLeaseMetadata(gl, ga)
		check("lease_roundtrip/"+c.Name, err == nil && s.CreateRPS > 0, s, "ok")
	}
	for _, c := range g.LeaseDecode {
		s, err := parseLeaseMetadata(c.Labels, c.Annotations)
		id := "lease_decode/" + c.Name
		if !c.Result.OK {
			check(id, err != nil, fmt.Sprint(s, err), "error")
			continue
		}
		var want leaseSettings
		if jerr := json.Unmarshal(c.Result.Value, &want); jerr != nil {
			check(id, false, fmt.Sprint(s, err), string(c.Result.Value)+" (not representable as Go int)")
			continue
		}
		check(id, err == nil && reflect.DeepEqual(s, want), fmt.Sprint(s, err), want)
	}
	for _, c := range g.DeriveMember {
		var cl extv1.SandboxClaim
		if err := json.Unmarshal(c.Claim, &cl); err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		got := deriveMember(&cl)
		check("derive_member/"+c.Name, reflect.DeepEqual(got, c.Member), got, c.Member)
	}
	for _, c := range g.Reconstruct {
		var claims []extv1.SandboxClaim
		for _, r := range c.Claims {
			var cl extv1.SandboxClaim
			if err := json.Unmarshal(r, &cl); err != nil {
				t.Fatal(err)
			}
			claims = append(claims, cl)
		}
		got, err := reconstructGroups(c.BatchID, claims)
		id := "reconstruct_groups/" + c.Name
		if !c.Result.OK {
			check(id, err != nil, fmt.Sprint(got, err), "error")
		} else {
			check(id, err == nil && reflect.DeepEqual(got, c.Result.Value), fmt.Sprint(got, err), c.Result.Value)
		}
	}
	for _, c := range g.ParseOrdinal {
		n, ok := parseOrdinal(c.BatchID, c.Name)
		eq := (c.Ordinal == nil && !ok) || (c.Ordinal != nil && ok && *c.Ordinal == n)
		check(fmt.Sprintf("parse_ordinal/%s/%s", c.BatchID, c.Name), eq, fmt.Sprint(n, ok), c.Ordinal)
	}
	for _, c := range g.ValidateID {
		err := validateBatchID(c.ID)
		check(fmt.Sprintf("validate_batch_id/%q", c.ID), (err == nil) == c.OK, err == nil, c.OK)
	}
	for _, c := range g.Stale {
		r, _ := time.Parse(time.RFC3339Nano, c.Renew)
		n, _ := time.Parse(time.RFC3339Nano, c.Now)
		got := isLeaseStale(r, c.Duration, n)
		check(fmt.Sprintf("is_lease_stale/%d/%s", c.Duration, c.Now), got == c.Stale, got, c.Stale)
	}
	for _, c := range g.Outcome {
		st := 0
		if c.Status != nil {
			st = *c.Status
		}
		got := createErrorOutcome(st, c.Attempt)
		check(fmt.Sprintf("create_error_outcome/%d/%d", st, c.Attempt), string(got) == c.Outcome, got, c.Outcome)
	}
	for _, c := range g.RetryAfter {
		d, ok := retryAfterSeconds(c.Header)
		eq := ok == c.Honoured && (!ok || (c.Delay != nil && *c.Delay == d))
		check(fmt.Sprintf("retry_after/%q", c.Header), eq, fmt.Sprint(d, ok), fmt.Sprint(c.Delay, c.Honoured))
	}
	for _, c := range g.Backoff {
		got := backoffDelay(c.Attempt, backoffBase, backoffCap, c.Rand)
		check(fmt.Sprintf("backoff/%d/%v", c.Attempt, c.Rand), got == c.Delay, got, c.Delay)
	}
	for _, c := range g.Shutdown {
		got, err := fillShutdownSeconds(c.Size, c.CreateRPS, c.QuorumTimeout, c.WorkBudget, time.Date(2026, 10, 20, 8, 0, 0, 0, time.UTC))
		if c.CreateRPS < 1e-100 && c.Size > 0 {
			// rev 3: the exact Python bound (datetime, year 9999) is golden-tested in TestShutdownBoundGolden.
			check(fmt.Sprintf("shutdown/%d/%v", c.Size, c.CreateRPS), err != nil, err, "Go rejects (Python raises in construct_sandbox_claim_lifecycle_spec)")
			continue
		}
		check(fmt.Sprintf("shutdown/%d/%v", c.Size, c.CreateRPS), err == nil && float64(got) == c.FillSeconds, got, c.FillSeconds)
		acq := int64(c.QuorumTimeout + c.WorkBudget + shutdownMarginSeconds)
		check(fmt.Sprintf("shutdown_acquire/%d", c.Size), acq == c.AcqSeconds, acq, c.AcqSeconds)
	}

	// Label validation: Go uses apimachinery's validators (what the apiserver enforces). Report, don't fail.
	var div []string
	for _, c := range g.LabelValidation {
		var goOK bool
		if c.Kind == "value" {
			goOK = len(validation.IsValidLabelValue(c.S)) == 0
		} else {
			goOK = len(validation.IsQualifiedName(c.S)) == 0
		}
		if goOK != c.OK {
			div = append(div, fmt.Sprintf("%s %q: python=%v go(apimachinery)=%v", c.Kind, trunc(c.S), c.OK, goOK))
		}
	}
	sort.Strings(div)
	t.Logf("label validation divergences (Python laxer => apiserver rejects later):\n  %s", strings.Join(div, "\n  "))
	t.Logf("checked %d golden cases, %d allowed divergences", checked, allowed)
}

func trunc(s string) string {
	if len(s) > 24 {
		return s[:24] + "…"
	}
	return s
}
